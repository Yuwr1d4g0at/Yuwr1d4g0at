// Builds the Pixel Quest profile: SVG panels in assets/ and README.md.
//
//   node scripts/build.mjs           live data when GITHUB_TOKEN is set, else "??" placeholders
//   DEMO=1 node scripts/build.mjs    sample data, for previewing locally
//
// OUT_DIR writes somewhere other than the repo root. THANK_GUESTBOOK=true makes
// the workflow reply to and close new guestbook signatures.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, esc } from './lib/svg.mjs';
import { fetchGitHub, thankGuestbook } from './lib/github.mjs';
import { pickSeason } from './lib/season.mjs';
import { demoData } from './lib/demo.mjs';
import * as P from './lib/panels.mjs';

const config = JSON.parse(readFileSync(join(ROOT, 'profile.json'), 'utf8'));
const tips = JSON.parse(readFileSync(join(ROOT, 'data', 'tips.json'), 'utf8'));
const OUT = process.env.OUT_DIR ?? ROOT;
const repoUrl = `https://github.com/${config.username}/${config.username}`;

let data = {
  stats: null,
  createdAt: null,
  publicRepos: null,
  quests: config.fallbackQuests,
  websiteUrl: config.website || null,
  calendar: null,
  guestbook: [],
};
if (process.env.DEMO) {
  data = demoData(config);
} else if (process.env.GITHUB_TOKEN) {
  try {
    const live = await fetchGitHub(config);
    data = { ...live, quests: live.quests.length ? live.quests : config.fallbackQuests };
  } catch (err) {
    console.error('GitHub API failed, using placeholders:', err.message);
  }
} else {
  console.log('No GITHUB_TOKEN: stats show ?? and quests come from profile.json.');
}

const now = new Date();
data.accountYears = data.createdAt
  ? Math.floor((now - new Date(data.createdAt)) / (365.25 * 864e5))
  : null;
const season = pickSeason(process.env.DEMO_SEASON ?? config.season, now, data.createdAt);
const todaysTip = tips[Math.floor(now / 864e5) % tips.length];

const links = {
  website: data.websiteUrl ?? `https://github.com/${config.username}/${config.websiteRepo}`,
  help: `${repoUrl}/issues/new?template=it-help.yml`,
  guestbook: `${repoUrl}/issues/new?template=guestbook.yml`,
};

function readme() {
  const questLinks = data.quests.map((q) => `[${q.name}](${q.url})`).join(' · ');
  return `<!-- Generated by scripts/build.mjs. Edit profile.json instead; the workflow rebuilds this file. -->
<div align="center">

<img src="assets/banner.svg" width="100%" alt="Pixel art goat beside the text: Player 1, ${esc(config.displayName)}. Class: ${esc(config.class)}. Alignment: ${esc(config.alignment)}">

<a href="${links.website}"><img src="assets/btn-website.svg" width="32%" alt="Visit my website"></a> <a href="${links.help}"><img src="assets/btn-help.svg" width="32%" alt="Ask for IT help"></a> <a href="${links.guestbook}"><img src="assets/btn-guestbook.svg" width="32%" alt="Sign the guestbook"></a>

<img src="assets/tip.svg" width="100%" alt="Tip of the day: ${esc(todaysTip)}">

<img src="assets/bio.svg" width="49%" alt="Bio: ${esc(config.bio.join('; '))}"> <img src="assets/inventory.svg" width="49%" alt="Inventory: ${esc(config.inventory.map((i) => i.label).join(', '))}">

<img src="assets/stats.svg" width="100%" alt="GitHub stats: commits, pull requests, stars and contribution streak">

<img src="assets/achievements.svg" width="100%" alt="Achievements unlocked from GitHub activity">

<img src="assets/map.svg" width="100%" alt="Contribution map with a pixel goat eating the grass">

<a href="https://github.com/${config.username}?tab=repositories"><img src="assets/quests.svg" width="100%" alt="Quest log: ${esc(data.quests.map((q) => q.name).join(', '))}"></a>

${questLinks}

<a href="${links.guestbook}"><img src="assets/guestbook.svg" width="100%" alt="Guestbook: latest visitors who signed"></a>

<img src="assets/footer.svg" width="100%" alt="Thanks for playing :3">

</div>
`;
}

const out = {
  'assets/banner.svg': P.banner({ config, level: data.stats?.level ?? null, season, accountYears: data.accountYears }),
  'assets/btn-website.svg': P.button('VISIT WEBSITE', '#41a6f6'),
  'assets/btn-help.svg': P.button('ASK FOR IT HELP', '#a7f070'),
  'assets/btn-guestbook.svg': P.button('SIGN GUESTBOOK', '#ff7eb6'),
  'assets/tip.svg': P.tip(todaysTip),
  'assets/bio.svg': P.bio(config),
  'assets/inventory.svg': P.inventory(config),
  'assets/stats.svg': P.stats(data.stats),
  'assets/achievements.svg': P.achievements(data),
  'assets/map.svg': P.worldMap(data.calendar),
  'assets/quests.svg': P.quests(data.quests),
  'assets/guestbook.svg': P.guestbook(data.guestbook, config.guestbookRows ?? 5),
  'assets/footer.svg': P.footer(),
  'README.md': readme(),
};
mkdirSync(join(OUT, 'assets'), { recursive: true });
for (const [path, content] of Object.entries(out)) writeFileSync(join(OUT, path), content);
console.log(`Wrote ${Object.keys(out).length} files (season: ${season ?? 'none'}, level: ${data.stats?.level ?? '??'})`);

if (process.env.THANK_GUESTBOOK === 'true' && !process.env.DEMO && data.guestbook.length) {
  try {
    await thankGuestbook(config, data.guestbook);
  } catch (err) {
    console.error('Could not reply to guestbook signatures:', err.message);
  }
}
