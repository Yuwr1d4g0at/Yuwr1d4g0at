// Builds the Pixel Quest profile: SVG panels in assets/ and README.md.
//
//   node scripts/build.mjs           live data when GITHUB_TOKEN is set, else placeholders
//   DEMO=1 node scripts/build.mjs    sample data, for previewing locally
//
// OUT_DIR writes somewhere other than the repo root. ANSWER_ISSUES=true makes
// the workflow reply to and close new guestbook signatures and button presses.
// WAKATIME_API_KEY adds the coding time panel.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, esc } from './lib/svg.mjs';
import { fetchGitHub, guestbookFrom, guestbookReplies, respond } from './lib/github.mjs';
import { fetchWakaTime } from './lib/wakatime.mjs';
import { simulate } from './lib/interactions.mjs';
import { MONSTERS } from './lib/monsters.mjs';
import { pickSeason } from './lib/season.mjs';
import { demoData } from './lib/demo.mjs';
import * as P from './lib/panels.mjs';

const config = JSON.parse(readFileSync(join(ROOT, 'profile.json'), 'utf8'));
const tips = JSON.parse(readFileSync(join(ROOT, 'data', 'tips.json'), 'utf8'));
const OUT = process.env.OUT_DIR ?? ROOT;
const repoUrl = `https://github.com/${config.username}/${config.username}`;

let data = {
  stats: null,
  createdAt: null,
  publicRepos: null,
  quests: config.fallbackQuests,
  websiteUrl: config.website || null,
  calendar: null,
  issues: [],
  activity: null,
  waka: null,
};
if (process.env.DEMO) {
  data = demoData(config);
} else {
  if (process.env.GITHUB_TOKEN) {
    try {
      const live = await fetchGitHub(config);
      data = { ...data, ...live, quests: live.quests.length ? live.quests : config.fallbackQuests };
    } catch (err) {
      console.error('GitHub API failed, using placeholders:', err.message);
    }
  } else {
    console.log('No GITHUB_TOKEN: stats show ?? and quests come from profile.json.');
  }
  try {
    data.waka = await fetchWakaTime();
  } catch (err) {
    console.error('WakaTime failed:', err.message);
  }
}

const now = new Date();
const day = Math.floor(now / 864e5);
data.accountYears = data.createdAt ? Math.floor((now - new Date(data.createdAt)) / (365.25 * 864e5)) : null;
data.guestbook = guestbookFrom(data.issues);
const game = simulate(
  data.issues.filter((i) => i.kind !== 'guestbook'),
  { born: config.goatBorn, now: now.toISOString() }
);
data.care = game.care;
data.boss = game.boss;

const season = pickSeason(process.env.DEMO_SEASON ?? config.season, now, data.createdAt);
const todaysTip = tips[day % tips.length];
const monster = config.encounters === false ? null : MONSTERS[(day * 7 + 3) % MONSTERS.length];

const issueLink = (title, body) =>
  `${repoUrl}/issues/new?title=${encodeURIComponent(title)}&body=${encodeURIComponent(body)}`;
const AUTO = '\n\nThis closes by itself in a minute or two, and the profile updates.';
const links = {
  feed: issueLink('[FEED] the goat', `Click **Submit new issue** to feed the goat! :3${AUTO}`),
  pet: issueLink('[PET] the goat', `Click **Submit new issue** to pet the goat! :3${AUTO}`),
  attack: issueLink('[ATTACK] the bug boss', `Click **Submit new issue** to attack the bug boss!${AUTO}`),
  website: data.websiteUrl ?? `https://github.com/${config.username}/${config.websiteRepo}`,
  help: `${repoUrl}/issues/new?template=it-help.yml`,
  guestbook: `${repoUrl}/issues/new?template=guestbook.yml`,
};

// The coding panel only shows once WakaTime is connected. If WakaTime is
// still crunching numbers, keep the last panel rather than dropping it.
const codingPath = join(OUT, 'assets', 'coding.svg');
const showCoding = Boolean(data.waka) || (Boolean(process.env.WAKATIME_API_KEY) && existsSync(codingPath));

function readme() {
  const questLinks = data.quests.map((q) => `[${q.name}](${q.url})`).join(' · ');
  const img = (file, alt, width = '100%') => `<img src="assets/${file}" width="${width}" alt="${esc(alt)}">`;
  return `<!-- Generated by scripts/build.mjs. Edit profile.json instead; the workflow rebuilds this file. -->
<div align="center">

${img('banner.svg', `Pixel art goat beside the text: Player 1, ${config.displayName}. Class: ${config.class}. Alignment: ${config.alignment}.${monster ? ` A wild ${monster.name} appeared!` : ''}`)}

<a href="${links.feed}">${img('btn-feed.svg', 'Feed the goat', '32%')}</a> <a href="${links.pet}">${img('btn-pet.svg', 'Pet the goat', '32%')}</a> <a href="${links.attack}">${img('btn-attack.svg', 'Attack the bug boss', '32%')}</a>

<sub>[my website](${links.website}) · [ask me for IT help](${links.help}) · [sign the guestbook](${links.guestbook})</sub>

${img('care.svg', `Goat care: food ${data.care.food}, love ${data.care.love}`, '49%')} ${img('boss.svg', `Boss fight: ${data.boss.name}, ${data.boss.current} of ${data.boss.hp} HP`, '49%')}

${img('tip.svg', `Tip of the day: ${todaysTip}`)}

${img('bio.svg', `Bio: ${config.bio.join('; ')}`, '49%')} ${img('inventory.svg', `Inventory: ${config.inventory.map((i) => i.label).join(', ')}`, '49%')}

${img('stats.svg', 'GitHub stats: commits, pull requests, stars and contribution streak')}
${showCoding ? `\n${img('coding.svg', 'Coding time in the last 7 days, from WakaTime')}\n` : ''}
${img('activity.svg', 'Activity clock: commits by hour of day and day of week')}

${img('achievements.svg', 'Achievements unlocked from GitHub activity')}

${img('map.svg', 'Contribution map with a pixel goat eating the grass')}

<a href="https://github.com/${config.username}?tab=repositories">${img('quests.svg', `Quest log: ${data.quests.map((q) => q.name).join(', ')}`)}</a>

${questLinks}

<a href="${links.guestbook}">${img('guestbook.svg', 'Guestbook: latest visitors who signed. Click to sign.')}</a>

${img('footer.svg', 'Thanks for playing :3')}

</div>
`;
}

const out = {
  'assets/banner.svg': P.banner({
    config,
    level: data.stats?.level ?? null,
    season,
    accountYears: data.accountYears,
    mood: data.care.mood,
    monster,
  }),
  'assets/btn-feed.svg': P.button('FEED GOAT', '#ef7d57'),
  'assets/btn-pet.svg': P.button('PET GOAT', '#ff7eb6'),
  'assets/btn-attack.svg': P.button('ATTACK BUG', '#a7f070'),
  'assets/care.svg': P.goatCare(data.care),
  'assets/boss.svg': P.bossFight(data.boss),
  'assets/tip.svg': P.tip(todaysTip),
  'assets/bio.svg': P.bio(config),
  'assets/inventory.svg': P.inventory(config),
  'assets/stats.svg': P.stats(data.stats),
  'assets/activity.svg': P.activityClock(data.activity),
  'assets/achievements.svg': P.achievements(data),
  'assets/map.svg': P.worldMap(data.calendar),
  'assets/quests.svg': P.quests(data.quests),
  'assets/guestbook.svg': P.guestbook(data.guestbook, config.guestbookRows ?? 5),
  'assets/footer.svg': P.footer(),
  'README.md': readme(),
};
if (data.waka) out['assets/coding.svg'] = P.coding(data.waka);

mkdirSync(join(OUT, 'assets'), { recursive: true });
for (const [path, content] of Object.entries(out)) writeFileSync(join(OUT, path), content);
console.log(
  `Wrote ${Object.keys(out).length} files (season: ${season ?? 'none'}, level: ${data.stats?.level ?? '??'}, goat: ${data.care.mood}, boss: ${data.boss.name} ${data.boss.current}/${data.boss.hp}, coding panel: ${showCoding})`
);

if (process.env.ANSWER_ISSUES === 'true' && !process.env.DEMO) {
  const replies = [...guestbookReplies(data.guestbook), ...game.replies];
  try {
    await respond(config, replies);
  } catch (err) {
    console.error('Could not answer issues:', err.message);
  }
}
